const SUPABASE_URL = process.env.VITE_SUPABASE_URL;
const SUPABASE_KEY = process.env.VITE_SUPABASE_PUBLISHABLE_KEY;
const GITHUB_TOKEN = process.env.GITHUB_TOKEN;
const REPO = "hazardno-dot/playnice-site";
const [OWNER, REPO_NAME] = REPO.split("/");
const CONFIG_PATH = "playnice-site/src/data/heroSlides.generated.js";
const EXHIBITION_PATH = "playnice-site/src/data/exhibition.js";

const json = (res, status, body) => res.status(status).json(body);

async function readJson(response, label) {
  const text = await response.text();
  try {
    return text ? JSON.parse(text) : null;
  } catch {
    throw new Error(`${label} returned a non-JSON response (${response.status}).`);
  }
}

async function supabaseFetch(path, token, options = {}) {
  return fetch(`${SUPABASE_URL}${path}`, {
    ...options,
    headers: {
      apikey: SUPABASE_KEY,
      Authorization: `Bearer ${token}`,
      "Content-Type": "application/json",
      Prefer: "return=representation",
      ...(options.headers || {}),
    },
  });
}

async function github(path, options = {}) {
  const response = await fetch(`https://api.github.com${path}`, {
    ...options,
    headers: {
      Authorization: `Bearer ${GITHUB_TOKEN}`,
      Accept: "application/vnd.github+json",
      "X-GitHub-Api-Version": "2022-11-28",
      "Content-Type": "application/json",
      ...(options.headers || {}),
    },
  });
  const data = await readJson(response, "GitHub API");
  if (!response.ok) {
    const error = new Error(data?.message || `GitHub request failed (${response.status}).`);
    error.status = response.status;
    throw error;
  }
  return data;
}

const stable = (value) => {
  const normalize = (item) => {
    if (Array.isArray(item)) return item.map(normalize);
    if (item && typeof item === "object") {
      return Object.keys(item).sort().reduce((out, key) => {
        out[key] = normalize(item[key]);
        return out;
      }, {});
    }
    return item;
  };
  return JSON.stringify(normalize(value ?? null));
};

function parseGeneratedConfig(source) {
  const marker = "export const BASE_HERO_SLIDES = ";
  const start = source.indexOf(marker);
  if (start < 0) throw new Error("Generated Hero config export was not found.");
  const raw = source.slice(start + marker.length).trim().replace(/;\s*$/, "");
  const parsed = JSON.parse(raw);
  if (!Array.isArray(parsed)) throw new Error("Generated Hero config is not an array.");
  return parsed;
}

function renderConfig(runtimeSlides) {
  return [
    "// Generated by PlayNice Control Center Hero Controlled Apply.",
    "// Source: approved Supabase Hero draft + verified Hero baseline.",
    "// Do not edit manually unless deliberately taking Hero management out of Control Center.",
    "",
    `export const BASE_HERO_SLIDES = ${JSON.stringify(runtimeSlides, null, 2)};`,
    "",
  ].join("\n");
}

function runtimeObject(slide = {}) {
  const out = {
    id: Number(slide.id),
    kind: slide.kind || "imageOnly",
    image: slide.desktopImage || slide.image || slide.desktop_image || "",
    desktopImage: slide.desktopImage || slide.image || slide.desktop_image || "",
    mobileImage: slide.mobileImage || slide.mobile_image || slide.image || "",
    alt: String(slide.alt || "").trim(),
    actionPrimary: slide.actionPrimary || slide.action_type || "none",
  };
  if (out.actionPrimary === "product") {
    out.actionProductSlug = slide.actionProductSlug || slide.product_slug || "";
    out.preferredSize = slide.preferredSize || slide.preferred_size || "10ml";
  } else if (out.actionPrimary === "collection") {
    out.actionCollection = Array.isArray(slide.actionCollection) ? slide.actionCollection : (Array.isArray(slide.collection_slugs) ? slide.collection_slugs : []);
    out.collectionTitle = slide.collectionTitle || slide.collection_title || "";
  } else if (out.actionPrimary === "manifesto") {
    out.manifestoType = slide.manifestoType || slide.manifesto_type || "";
  }
  return out;
}

function safeId(value) {
  return String(value || "").trim().toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
}

function periodFor(date = new Date()) {
  const year = date.getUTCFullYear();
  const month = date.getUTCMonth() + 1;
  if (month <= 4) return { year, period: `feb-apr-${year}` };
  if (month <= 8) return { year, period: `may-aug-${year}` };
  return { year, period: `sep-dec-${year}` };
}

function buildExhibitionEntry(heroKey, baseline) {
  const { year, period } = periodFor();
  const entryId = `hero-${safeId(heroKey)}`;
  const candidates = [
    { suffix: "desktop", src: baseline.desktopImage || baseline.image || "", format: "wide" },
    { suffix: "mobile", src: baseline.mobileImage || baseline.image || "", format: "mobile" },
  ];
  const seen = new Set();
  const assets = candidates
    .filter((asset) => asset.src && !seen.has(asset.src) && seen.add(asset.src))
    .map((asset) => ({ id: `${entryId}-${asset.suffix}`, type: "image", src: asset.src, format: asset.format, alt: baseline.alt || heroKey }));
  if (!assets.length) throw new Error("Retired Hero has no reusable Exhibition image asset.");
  return {
    id: entryId,
    year,
    period,
    title: String(baseline.alt || heroKey).trim(),
    kind: "campaign",
    status: "archived",
    published: true,
    label: { sr: "Hero kampanja", en: "Hero Campaign" },
    line: { sr: "Kampanja je završena. Ideja ostaje.", en: "The campaign is over. The idea remains." },
    assets,
  };
}

function insertExhibitionEntry(source, entry) {
  const marker = "export const exhibitionItems = [\n";
  const index = source.indexOf(marker);
  if (index < 0) throw new Error("Could not locate Exhibition data array.");
  const duplicateNeedles = [`id: \"${entry.id}\"`, `\"id\": \"${entry.id}\"`];
  if (duplicateNeedles.some((needle) => source.includes(needle))) return { source, alreadyPresent: true };
  const rendered = `  ${JSON.stringify(entry, null, 2).replace(/\n/g, "\n  ")},\n\n`;
  return { source: source.slice(0, index + marker.length) + rendered + source.slice(index + marker.length), alreadyPresent: false };
}

export default async function handler(req, res) {
  if (req.method !== "POST") return json(res, 405, { error: "Method not allowed." });
  if (!SUPABASE_URL || !SUPABASE_KEY || !GITHUB_TOKEN) return json(res, 500, { error: "Hero retirement environment is incomplete." });

  const authHeader = req.headers.authorization || "";
  const token = authHeader.startsWith("Bearer ") ? authHeader.slice(7) : "";
  const heroKey = String(req.body?.hero_key || "").trim();
  if (!token) return json(res, 401, { error: "Admin session required." });
  if (!heroKey) return json(res, 400, { error: "hero_key is required." });

  let branch = "";
  let prNumber = null;

  try {
    const userResponse = await fetch(`${SUPABASE_URL}/auth/v1/user`, { headers: { apikey: SUPABASE_KEY, Authorization: `Bearer ${token}` } });
    const user = await readJson(userResponse, "Supabase Auth");
    if (!userResponse.ok || !user?.id) return json(res, 401, { error: "Admin session expired." });

    const adminResponse = await supabaseFetch(`/rest/v1/admin_users?user_id=eq.${encodeURIComponent(user.id)}&select=user_id`, token);
    const admins = await readJson(adminResponse, "Supabase admin lookup");
    if (!adminResponse.ok || !Array.isArray(admins) || !admins.length) return json(res, 403, { error: "PlayNice admin access required." });

    const draftResponse = await supabaseFetch(`/rest/v1/hero_drafts?hero_key=eq.${encodeURIComponent(heroKey)}&select=hero_key,payload,approved_payload,review_status,baseline_snapshot,apply_branch,apply_pr_number`, token);
    const drafts = await readJson(draftResponse, "Supabase Hero draft");
    if (!draftResponse.ok) throw new Error(drafts?.message || "Could not read Hero draft.");
    const draft = drafts?.[0];
    if (!draft) return json(res, 404, { error: "Hero draft not found." });
    if (draft.review_status !== "approved" || !draft.approved_payload) return json(res, 409, { error: "Hero draft must be approved before retirement apply." });
    if (stable(draft.payload) !== stable(draft.approved_payload)) return json(res, 409, { error: "APPROVAL SAFETY BLOCK: current draft differs from the approved snapshot." });
    if (draft.apply_branch || draft.apply_pr_number) return json(res, 409, { error: "A Hero preview branch already exists for this draft." });
    if (draft.baseline_snapshot?.enabled === false || draft.approved_payload?.enabled !== false) {
      return json(res, 409, { error: "This endpoint only accepts active → inactive Hero retirement drafts." });
    }

    const baseline = draft.baseline_snapshot;
    const baselineRuntime = runtimeObject(baseline);

    const mainRef = await github(`/repos/${OWNER}/${REPO_NAME}/git/ref/heads/main`);
    const baseSha = mainRef.object.sha;
    const configFile = await github(`/repos/${OWNER}/${REPO_NAME}/contents/${CONFIG_PATH}?ref=main`);
    const configSource = Buffer.from(configFile.content, "base64").toString("utf8");
    const runtimeSlides = parseGeneratedConfig(configSource);
    const liveSlide = runtimeSlides.find((slide) => Number(slide.id) === Number(baseline.id));
    if (!liveSlide) return json(res, 409, { error: "LIVE DRIFT: Hero is already absent from main runtime." });
    if (stable(runtimeObject(liveSlide)) !== stable(baselineRuntime)) {
      return json(res, 409, { error: "LIVE DRIFT: main Hero slide no longer matches the approved retirement baseline." });
    }

    const nextRuntime = runtimeSlides.filter((slide) => Number(slide.id) !== Number(baseline.id));
    if (nextRuntime.length !== runtimeSlides.length - 1) return json(res, 409, { error: "Retirement must remove exactly one Hero slide." });

    const stamp = new Date().toISOString().replace(/[-:TZ.]/g, "").slice(0, 12);
    const safeKey = heroKey.replace(/[^a-z0-9-]/gi, "-").toLowerCase();
    branch = `cc-hero-apply-${safeKey}-${stamp}`;
    await github(`/repos/${OWNER}/${REPO_NAME}/git/refs`, { method: "POST", body: JSON.stringify({ ref: `refs/heads/${branch}`, sha: baseSha }) });

    const branchConfig = await github(`/repos/${OWNER}/${REPO_NAME}/contents/${CONFIG_PATH}?ref=${encodeURIComponent(branch)}`);
    await github(`/repos/${OWNER}/${REPO_NAME}/contents/${CONFIG_PATH}`, {
      method: "PUT",
      body: JSON.stringify({ message: `Retire Hero from runtime: ${heroKey}`, content: Buffer.from(renderConfig(nextRuntime), "utf8").toString("base64"), sha: branchConfig.sha, branch }),
    });

    const exhibitionEntry = buildExhibitionEntry(heroKey, baseline);
    const exhibitionFile = await github(`/repos/${OWNER}/${REPO_NAME}/contents/${EXHIBITION_PATH}?ref=${encodeURIComponent(branch)}`);
    const exhibitionSource = Buffer.from(exhibitionFile.content, "base64").toString("utf8");
    const preparedExhibition = insertExhibitionEntry(exhibitionSource, exhibitionEntry);
    if (!preparedExhibition.alreadyPresent) {
      await github(`/repos/${OWNER}/${REPO_NAME}/contents/${EXHIBITION_PATH}`, {
        method: "PUT",
        body: JSON.stringify({ message: `Archive retired Hero in Exhibition: ${heroKey}`, content: Buffer.from(preparedExhibition.source, "utf8").toString("base64"), sha: exhibitionFile.sha, branch }),
      });
    }

    const pr = await github(`/repos/${OWNER}/${REPO_NAME}/pulls`, {
      method: "POST",
      body: JSON.stringify({
        title: `Control Center Hero retirement: ${heroKey}`,
        head: branch,
        base: "main",
        draft: true,
        body: [
          "Generated by PlayNice Control Center Hero Retirement v1.",
          "",
          `- Hero: ${heroKey}`,
          `- Slide ID: ${baseline.id}`,
          `- Hero runtime: removed from ${CONFIG_PATH}`,
          `- Exhibition archive: ${exhibitionEntry.id} → ${EXHIBITION_PATH}`,
          `- Exhibition period: ${exhibitionEntry.period}`,
          `- Reused assets: ${exhibitionEntry.assets.map((asset) => asset.src).join(", ")}`,
          "- Source: approved_payload + frozen baseline_snapshot",
          "- Safety: active → inactive retirement only",
          "- Safety: main runtime parity checked before branch creation",
          "- Safety: one draft PR only; no automatic merge",
        ].join("\n"),
      }),
    });
    prNumber = pr.number;

    const now = new Date().toISOString();
    const patchResponse = await supabaseFetch(`/rest/v1/hero_drafts?hero_key=eq.${encodeURIComponent(heroKey)}`, token, {
      method: "PATCH",
      body: JSON.stringify({
        apply_branch: branch,
        apply_pr_number: pr.number,
        apply_created_at: now,
        apply_created_by: user.id,
        preview_verified_at: null,
        preview_verified_by: null,
      }),
    });
    if (!patchResponse.ok) {
      const patchBody = await readJson(patchResponse, "Supabase Hero retirement metadata");
      throw new Error(patchBody?.message || "Could not save Hero retirement apply metadata.");
    }

    return json(res, 200, {
      ok: true,
      branch,
      pr_number: pr.number,
      pr_url: pr.html_url,
      retirement: true,
      exhibition_id: exhibitionEntry.id,
      files: [CONFIG_PATH, EXHIBITION_PATH],
      assets: exhibitionEntry.assets.map((asset) => asset.src),
    });
  } catch (error) {
    console.error("Hero retirement apply failed", { heroKey, branch, prNumber, error: error?.message || String(error) });
    if (branch && !prNumber) {
      try {
        await github(`/repos/${OWNER}/${REPO_NAME}/git/refs/heads/${encodeURIComponent(branch)}`, { method: "DELETE" });
      } catch (cleanupError) {
        console.error("Hero retirement branch cleanup failed", cleanupError?.message || cleanupError);
      }
    }
    return json(res, 500, { error: error?.message || "Hero retirement apply failed." });
  }
}
