import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const source = fs.readFileSync(path.resolve(here, "../src/JournalApplyManager.jsx"), "utf8");
assert.match(source, /review_status !== "approved"/, "apply controls must only render for approved drafts");
assert.match(source, /prepared_at/, "UI must distinguish prepared state");
assert.match(source, /apply_pr_number/, "UI must expose created PR state");
assert.match(source, /action === "prepare"/, "UI must send explicit prepare action");
assert.match(source, /Create draft PR/, "UI must expose draft PR creation");
assert.match(source, /Refresh draft PR/, "UI must expose same-PR refresh after fresh prepare");
assert.match(source, /Prepare refresh/, "UI must require a fresh preparation before refreshing an existing PR");
assert.match(source, /target="_blank"/, "created PR must be directly openable");
assert.match(source, /comparablePayload/, "post-merge reconciliation must compare live and draft payloads without transient media staging metadata");
assert.match(source, /\/api\/sync-journal-publish-status/, "post-merge reconciliation must use the authenticated server-side publish sync endpoint");
assert.match(source, /Authorization: `Bearer \$\{token\}`/, "Journal publish reconciliation must forward the authenticated admin session");
assert.match(source, /payload\.status !== "published"/, "UI must only clear local Journal state after server-confirmed publication");
assert.doesNotMatch(source, /REPO_PULLS_URL/, "Journal UI must not call GitHub PR API directly");
assert.doesNotMatch(source, /api\.github\.com\/repos\/hazardno-dot\/playnice-site\/pulls/, "Journal UI must keep GitHub reconciliation server-side");
assert.doesNotMatch(source, /\.from\("journal_drafts"\)\s*\.delete\(\)/s, "Journal UI must not delete published drafts directly");
assert.match(source, /window\.location\.reload\(\)/, "successful server-side reconciliation must immediately refresh the Journal UI so published drafts show LIVE ONLY without manual F5");
console.log("PASS  Journal Controlled Apply UI state contract");
console.log("PASS  existing Journal draft PR requires fresh prepare and can refresh in place");
