import assert from "node:assert/strict";
import { ReservationSpecification } from "../lib/inventory-reservation-simulator.mjs";
const item=(productKey,sizeMl,quantity=1)=>({productKey,sizeMl,quantity});
const s=new ReservationSpecification({naxos:80,ginger:30});
const a=s.commitNewOrder({orderId:"A",fingerprint:"hash-a",items:[item("naxos",20,2)]});
const b=s.commitNewOrder({orderId:"B",fingerprint:"hash-b",items:[item("naxos",20,2)]});
const race=s.commitNewOrder({orderId:"C",fingerprint:"hash-c",items:[item("naxos",20)]});
assert.equal(a.ok,true);
assert.equal(b.ok,true);
assert.equal(race.reason,"INSUFFICIENT_AVAILABLE");
assert.deepEqual(s.view("naxos"),{physicalMl:80,reservedMl:80,availableMl:0});
assert.deepEqual(s.commitNewOrder({orderId:"A",fingerprint:"hash-a",items:[item("naxos",20,2)]}),{ok:true,duplicate:true});
assert.equal(s.commitNewOrder({orderId:"A",fingerprint:"different",items:[item("naxos",20)]}).reason,"IDEMPOTENCY_CONFLICT");
assert.equal(s.packOrder("A").ok,true);
assert.deepEqual(s.view("naxos"),{physicalMl:40,reservedMl:40,availableMl:0});
assert.deepEqual(s.packOrder("A"),{ok:true,duplicate:true});
assert.equal(s.cancelUnpacked("A").reason,"RECONCILIATION_REQUIRED");
assert.equal(s.cancelUnpacked("B").ok,true);
assert.deepEqual(s.view("naxos"),{physicalMl:40,reservedMl:0,availableMl:40});
assert.deepEqual(s.cancelUnpacked("B"),{ok:true,duplicate:true});
const mixed=s.commitNewOrder({orderId:"D",fingerprint:"hash-d",items:[item("naxos",20,2),item("ginger",20,2)]});
assert.equal(mixed.reason,"INSUFFICIENT_AVAILABLE");
assert.deepEqual(s.view("naxos"),{physicalMl:40,reservedMl:0,availableMl:40});
assert.deepEqual(s.view("ginger"),{physicalMl:30,reservedMl:0,availableMl:30});
assert.equal(s.commitNewOrder({orderId:"E",fingerprint:"hash-e",items:[item("unknown",5)]}).reason,"UNVERIFIED_STOCK");
assert.equal(s.commitNewOrder({orderId:"F",fingerprint:"hash-f",environment:"preview",items:[item("naxos",5)]}).reason,"PREVIEW_SEPARATE_LEDGER_REQUIRED");
assert.equal(s.commitNewOrder({orderId:"G",fingerprint:"hash-g",items:[item("naxos",20),item("naxos",10,2)]}).ok,true);
assert.deepEqual(s.view("naxos"),{physicalMl:40,reservedMl:40,availableMl:0});
assert.equal(s.commitNewOrder({orderId:"H",fingerprint:"hash-h",items:[item("naxos",0)]}).reason,"INVALID_ITEM");
console.log("PASS atomic-reservation specification: race, idempotency, pack/cancel, multi-size, all-or-nothing");
